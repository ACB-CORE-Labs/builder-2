from typing import Literal

ToolTier = Literal["tier1", "tier2", "notes"]
ToolStatus = Literal["installed", "missing", "optional-ui"]


@dataclass(frozen=True)
class ExternalTool:
    name: str
    command: str | None
    tier: ToolTier
    category: str
    role: str
    install: str
    required: bool = False
    integration: str = "detect-only"
    open_source: bool = True


@dataclass(frozen=True)
class ToolCheck:
    tool: ExternalTool
    status: ToolStatus
    version: str | None
    path: str | None


