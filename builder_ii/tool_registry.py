def tool_registry() -> tuple[ExternalTool, ...]:
    return TOOLS


def tools_by_tier(tier: ToolTier) -> tuple[ExternalTool, ...]:
    return tuple(tool for tool in TOOLS if tool.tier == tier)


def _version_for(command: str) -> str | None:
    probes = ([command, "--version"], [command, "version"])
    for probe in probes:
        try:
            proc = subprocess.run(probe, capture_output=True, text=True, timeout=5)
        except (OSError, subprocess.SubprocessError):
            continue
        text = (proc.stdout or proc.stderr).strip().splitlines()
        if proc.returncode == 0 and text:
            return text[0]
    return None


def check_tool(tool: ExternalTool) -> ToolCheck:
    if tool.command is None:
        status: ToolStatus = "optional-ui" if not tool.required else "installed"
        return ToolCheck(tool, status, None, None)
    path = shutil.which(tool.command)
    if not path:
        return ToolCheck(tool, "missing", None, None)
    return ToolCheck(tool, "installed", _version_for(tool.command), path)


def check_tools(*, tier: ToolTier | None = None) -> tuple[ToolCheck, ...]:
    tools = tools_by_tier(tier) if tier else TOOLS
    return tuple(check_tool(tool) for tool in tools)


def missing_required_tools() -> tuple[ToolCheck, ...]:
    return tuple(check for check in check_tools() if check.tool.required and check.status == "missing")
